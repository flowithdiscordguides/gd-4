// Builds SVG markup for either solid path icons or custom toolbar-line markup.
function iconMarkup(icon) {
  const viewBox = icon.viewBox || "0 0 100 100";
  const body = icon.markup || `<path fill="currentColor" stroke="none" d="${icon.path}"></path>`;
  return `
    <svg aria-hidden="true" focusable="false" viewBox="${viewBox}">
      <title>${icon.title}</title>
      ${body}
    </svg>
  `;
}

// Replaces one toolbar button's existing inline SVG while preserving its label, title, and tab behavior.
function replaceToolbarIcon(tabName, icon) {
  const button = document.querySelector(`.tab-button[data-tab="${tabName}"]`);
  if (!button) {
    return;
  }
  button.innerHTML = iconMarkup(icon);
}

// Installs the requested toolbar icons after static toolbar markup exists in the document.
function installToolbarIcons() {
  Object.keys(TOOLBAR_ICONS).forEach((tabName) => {
    replaceToolbarIcon(tabName, TOOLBAR_ICONS[tabName]);
  });
}

// Runs the replacement immediately when possible, or waits for the initial document parse.
function onReady(callback) {
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", callback);
    return;
  }
  callback();
}

